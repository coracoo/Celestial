/**
 * 带线性阻尼时，爬升 `h` 所需的初速（数值解，不走解析式）。
 *
 * 为什么不能直接用 `v=√(2gh)`：球道里虽然把阻尼降到 0.02，但它不是 0，
 * 而竖直爬近 30bu 的路上阻尼累积的相对能耗并不小。实测解析值 71.5 时
 * 实际只爬到 28.1bu（差 1bu 就够不着道顶拐弯板），所以这条线必须实测。
 *
 * 用 RK4 数值积分 `dv/dt = -g - d·v`，`dy/dt = v`，二分反解。
 */
export function climbSpeedFor(gravity: number, height: number, damping: number): number {
  const g = Math.abs(gravity);
  const dt = 1 / 2000;
  const climb = (v0: number): number => {
    let y = 0;
    let v = v0;
    while (v > 0.01 && y < height * 2) {
      // 半隐式欧拉：阻尼项 `d·v` 在高速下占比大，显式欧拉会发散
      v += (-g - damping * v) * dt;
      y += v * dt;
    }
    return y;
  };
  let lo = 1;
  let hi = 400;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (climb(mid) >= height) hi = mid;
    else lo = mid;
  }
  return hi;
}

/**
 * 每关的弹射力度区间。
 *
 * 这个区间只管一件事：**保证球一定爬得到交汇处**。爬上去之后怎么飞，
 * 由 `buildPlunger` 算出的出射速度区间决定，两件事互不干涉。
 *
 * **下限** = 刚好爬到交汇处的临界速度 ×1.18。
 * 系数不能更小：临界速度意味着「到顶时速度恰好为 0」，而球是被**逐帧**判定
 * 是否到达交汇处的，余量不够就会在最后几十 bu 反复上不去、掉回道底。
 * 1.18 留出的余速约 17%，够球稳稳越过触发线。
 *
 * **上限** = 下限 × `powerSpread`。这里曾经还有一个「别撞天花板」的约束，
 * 现在没有了：球一到交汇处就被折向左上方，**再也不会竖直冲上去**，
 * 天花板不再是任何一发力度的风险点。上限现在纯粹是手感问题——
 * 行程拉得越长，玩家在中低力度那段（斜率最陡）才越有分辨率。
 */
export function plungerPowerRange(gravity: number, height: number): { min: number; max: number } {
  const critical = climbSpeedFor(gravity, height, PLUNGER.laneDamping);
  const min = Math.max(PLUNGER.minPower, Math.ceil(critical * 1.18));
  const max = Math.max(PLUNGER.maxPower, Math.ceil(min * PLUNGER.powerSpread));
  return { min, max: Math.max(max, min + 1) };
}

