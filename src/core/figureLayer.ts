/**
 * 「角色」这一层立绘的文件名——**全项目只有这一处定义**。
 *
 * 为什么不各写各的：76e873f 那次管线把角色层从 `subject.png` 改名成
 * `subject-bleed.png`（同一个角色多出一圈出血，卡面靠它探出卡沿），
 * 卡面渲染器跟着改了，但剧情立绘、技能面板头像、技能释放演出这三处
 * 还指着旧文件名。三处全部静默失败——`<img>` 加载不到就 `hidden`，
 * 屏幕上只剩名牌，没有任何报错，`img.onerror` 也没人看。
 * 文件名散在四个文件里，每一次管线改名都要靠人记得改齐。
 *
 * 所以规则是：**谁都不许再写死角色层的文件名**，连卡面渲染器也从这里取。
 * 真要改名，改这一个常量，然后跑 `scripts/figure-assets.test.ts`
 * （它逐个断言名册里每个角色的这张图真的在磁盘上），当场就会红。
 */

/** 角色层在 `public/art/layers/<id>/` 下的文件名（不含扩展名）。 */
export const FIGURE_LAYER = 'subject-bleed';

/**
 * 出血画布 → 卡面 的放大倍数：1280/1024 = 1920/1536 = 1.25。
 *
 * 角色层画在**出血画布**上（比卡面大 128×192，四边各留一圈），
 * 而这三个 2D 场景要的是当年那张 1024×1536 的卡面构图。
 * 出血是**等比的**（两向都恰好 1.25），所以把图放大 1.25 倍、
 * 再往左上各挪 12.5%，就正好把出血裁掉，构图和旧图一致。
 * 各处 CSS 里的 `125%` / `-12.5%` 就是这个数，别单独改。
 */
export const FIGURE_BLEED_SCALE = 1.25;

/** 角色立绘的相对路径。`base` 默认给 public/ 下的相对路径。 */
export function figureUrl(id: string, base = 'art/layers/'): string {
  return `${base}${id}/${FIGURE_LAYER}.png`;
}
